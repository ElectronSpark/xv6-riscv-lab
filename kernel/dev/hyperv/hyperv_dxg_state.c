static uint32 hvdxg_parse_hex32(const char *s, const char **end)
{
    uint32 value = 0;

    if (s[0] == '0' && (s[1] == 'x' || s[1] == 'X'))
        s += 2;
    while (*s != '\0') {
        uint32 digit;

        if (*s >= '0' && *s <= '9')
            digit = (uint32)(*s - '0');
        else if (*s >= 'a' && *s <= 'f')
            digit = (uint32)(*s - 'a') + 10;
        else if (*s >= 'A' && *s <= 'F')
            digit = (uint32)(*s - 'A') + 10;
        else
            break;
        value = (value << 4) | digit;
        s++;
    }
    if (end != NULL)
        *end = s;
    return value;
}

