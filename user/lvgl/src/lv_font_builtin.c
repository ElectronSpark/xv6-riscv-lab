/* ── Drawing primitives ──────────────────────────────────────────── */

void lv_font_draw_char(uint32_t *buf, int buf_w, int buf_h,
                        int x, int y, char ch, lv_color_t color)
{
    if (ch < 32 || ch > 126)
        return;

    /* Whole-glyph clip rejection */
    if (g_clip_active) {
        if (x + 8 <= g_clip_x1 || x >= g_clip_x2 ||
            y + 16 <= g_clip_y1 || y >= g_clip_y2)
            return;
    }

    const uint8_t *glyph = font8x16[ch - 32];
    uint32_t pixel = ((uint32_t)color.alpha << 24) | ((uint32_t)color.red << 16) |
                     ((uint32_t)color.green << 8) | (uint32_t)color.blue;

    for (int row = 0; row < 16; row++) {
        int py = y + row;
        if (py < 0 || py >= buf_h)
            continue;
        if (g_clip_active && (py < g_clip_y1 || py >= g_clip_y2))
            continue;
        uint8_t bits = glyph[row];
        for (int col = 0; col < 8; col++) {
            int px = x + col;
            if (px < 0 || px >= buf_w)
                continue;
            if (g_clip_active && (px < g_clip_x1 || px >= g_clip_x2))
                continue;
            if (bits & (0x80 >> col))
                buf[py * buf_w + px] = pixel;
        }
    }
}

void lv_font_draw_string(uint32_t *buf, int buf_w, int buf_h,
                          int x, int y, const char *str, lv_color_t color)
{
    int cx = x;
    while (*str) {
        if (*str == '\n') {
            y += LV_FONT_HEIGHT;
            cx = x;
        } else {
            lv_font_draw_char(buf, buf_w, buf_h, cx, y, *str, color);
            cx += LV_FONT_WIDTH;
        }
        str++;
    }
}

void lv_font_measure(const char *text, int *out_w, int *out_h)
{
    int w = 0, max_w = 0, h = LV_FONT_HEIGHT;
    while (*text) {
        if (*text == '\n') {
            if (w > max_w) max_w = w;
            w = 0;
            h += LV_FONT_HEIGHT;
        } else {
            w += LV_FONT_WIDTH;
        }
        text++;
    }
    if (w > max_w) max_w = w;
    if (out_w) *out_w = max_w;
    if (out_h) *out_h = h;
}
